<?php
// ═══════════════════════════════════════════════════════════════════════════════
//  /signin — посадочная точка после входа через настоящий accounts.google.com.
//  Ссылка «Sign in» (yt_signin_url) ведёт на ServiceLogin с continue на
//  www.youtube.com/signin?next=…; под Fiddler'ом этот адрес — наш сервер, и
//  Google приводит человека сюда уже с куками аккаунта. Остаётся вернуть его
//  на страницу, с которой он уходил. Куки не трогаем — они и есть «вход».
// ═══════════════════════════════════════════════════════════════════════════════
$next = (string)($_GET['next'] ?? '/');
// Только локальный путь: чужой хост или протокол — это open redirect.
if ($next === '' || $next[0] !== '/' || str_starts_with($next, '//') || str_contains($next, '\\')) {
    $next = '/';
}
header('Location: ' . $next, true, 302);
exit;
